// Builds src/data/england-stats.js from data/player_stats.csv (the owner's dataset).
// Run from the project root: node scripts/import-stats.mjs
// The CSV has no quoted fields and no commas inside fields, so a plain split is safe.
import { readFileSync, writeFileSync } from 'node:fs';
import { ALL_ATTRS } from '../src/player.js';
import { matchStats, calibrate } from '../src/data/attrmap.js';
import premierLeague from '../src/data/england/premier-league.js';
import championship from '../src/data/england/championship.js';
import leagueOne from '../src/data/england/league-one.js';

const [head, ...lines] = readFileSync(new URL('../data/player_stats.csv', import.meta.url), 'utf8').trim().split(/\r?\n/);
const cols = head.split(',');
const rows = lines.map(line => Object.fromEntries(line.split(',').map((v, i) => [cols[i], v.trim()])));

const leagues = [premierLeague, championship, leagueOne];
const { stats, report } = matchStats(rows, leagues);
const calibration = calibrate(stats, leagues);

const body = Object.entries(stats).map(([club, players]) =>
  `  ${JSON.stringify(club)}: {\n${Object.entries(players).map(([n, a]) => `    ${JSON.stringify(n)}: ${JSON.stringify(a)},`).join('\n')}\n  },`).join('\n');
writeFileSync(new URL('../src/data/england-stats.js', import.meta.url),
  `// Generated by scripts/import-stats.mjs from data/player_stats.csv. Do not edit by hand; re-run the script.\n`
  + `// Each array holds: ${ALL_ATTRS.join(', ')}\nexport default {\n${body}\n};\n`
  + `// Whole-number shift added to every data rating in that league, so players without imported\n`
  + `// attributes sit on the same scale as those with them.\n`
  + `export const CALIBRATION = ${JSON.stringify(calibration).replace(/":/g, '": ').replace(/,/g, ', ').replace('{', '{ ').replace('}', ' }')};\n`);
writeFileSync(new URL('../.superpowers/sdd/1b/import-different-club.txt', import.meta.url), report.differentClub.join('\n') + '\n');

for (const league of leagues) {
  const total = league.clubs.reduce((n, c) => n + c.players.length, 0);
  const matched = league.clubs.reduce((n, c) => n + Object.keys(stats[c.name] || {}).length, 0);
  console.log(`${league.name}: ${matched} of ${total} players matched`);
}
console.log(`Calibration (shift per league): ${JSON.stringify(calibration)}`);
for (const k of ['ageRejected', 'ambiguous', 'keeperMismatch', 'duplicateRow'])
  console.log(`${k} (${report[k].length}): ${report[k].join('; ') || 'none'}`);
console.log(`differentClub (${report.differentClub.length}): full list in .superpowers/sdd/1b/import-different-club.txt`);
